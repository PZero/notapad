"""Post 7 – carosello "16.5 x 38 mm, 4 layers" (Instagram 4:5)."""
from comune import *
OUT = os.path.join(D, '07_inside-the-board'); N = 5
slides = []

# 1 – copertina
im = velo(sfondo('04_exploded-board_iphone.png', 140), alto=560, basso=260); d = ImageDraw.Draw(im)
etichetta(d, (80, 86), 'Inside the board')
y = testo(d, (80, 132), '16.5 × 38 mm. Four layers. Everything on one side.', f(SB, 62))
testo(d, (80, y + 10), 'Swipe for a tour of the brain of notªpad.', f(R_, 34), MUTE)
marchio(d); numero(d, 1, N); slides.append(im)

# 2 – le tre zone
im = Image.new('RGB', (W, H), BG); d = ImageDraw.Draw(im)
etichetta(d, (80, 70), 'Three zones, top to bottom')
sch = Image.open(os.path.join(R, 'kicad', 'anteprima.png')).convert('RGB').crop((103, 89, 1014, 2186))
hb = 1060; k = hb / sch.height; sch = sch.resize((int(sch.width * k), hb), Image.LANCZOS)
x0, y0 = 80, 140; im.paste(sch, (x0, y0)); mm = hb / 38
xt = x0 + sch.width + 70
zone = [(0, 7, 'A · top 7 mm', 'Charging contacts, top microphone, charger, power latch.'),
        (7, 20, 'B · middle', 'Three RGB lights, 256 MB of storage, front microphone, touch and motion sensors.'),
        (20, 38, 'C · bottom', 'Bluetooth module (nRF52840). Its antenna gets a clear zone: no copper, no battery under it.')]
for a, b, tit, sub in zone:
    ya, yb = y0 + a * mm, y0 + b * mm
    if a: d.line((x0 + sch.width + 8, ya, W - 60, ya), fill=(70, 68, 64), width=2)
    yy = testo(d, (xt, ya + 14), tit, f(SB, 36), LED if a == 20 else INK, larg=W - xt - 50)
    testo(d, (xt, yy + 2), sub, f(R_, 27), MUTE, larg=W - xt - 50, inter=1.25)
marchio(d); numero(d, 2, N); slides.append(im)

# 3 – quattro strati
im = Image.new('RGB', (W, H), BG); d = ImageDraw.Draw(im)
etichetta(d, (80, 86), 'Four copper layers')
y = testo(d, (80, 132), 'A board 1 mm thin, routed on four layers.', f(SB, 56))
st = Image.open(os.path.join(R, 'kicad', 'sbroglio.png')).convert('RGB').crop((50, 232, 2010, 1215))
st = st.resize((W - 120, int(st.height * (W - 120) / st.width)), Image.LANCZOS)
card = Image.new('RGB', (st.width + 24, st.height + 24), (245, 243, 238)); card.paste(st, (12, 12))
im.paste(card, (48, int(y + 40))); y = y + 40 + card.height + 40
for riga in ['Top: components and signals.', 'Layer 2: one solid ground plane.', 'Layer 3: signals and power.', 'Bottom: signals and ground.']:
    y = testo(d, (80, y), riga, f(R_, 32), MUTE) + 4
marchio(d); numero(d, 3, N); slides.append(im)

# 4 – generata dal codice
im = Image.new('RGB', (W, H), BG); d = ImageDraw.Draw(im)
etichetta(d, (80, 86), 'Not drawn by hand', BRONZE)
y = testo(d, (80, 132), 'The whole board is generated by code.', f(SB, 62))
y = testo(d, (80, y + 20), 'One Python file lists every part, connection and position. Scripts build the schematic, route 4 layers and write the factory files.', f(R_, 34), MUTE, inter=1.3)
y += 50
for n, s in [('130', 'vias'), ('0', 'design-rule errors'), ('71', 'automated checks before we order')]:
    d.text((80, y), n, font=f(B, 88), fill=LED); d.text((330, y + 34), s, font=f(R_, 38), fill=INK); y += 125
testo(d, (80, y + 20), 'The checks already caught a microphone rotated the wrong way in the assembly file.', f(R_, 32), MUTE, inter=1.3)
marchio(d); numero(d, 4, N); slides.append(im)

# 5 – chiusura
im = velo(sfondo('03_gold-contacts_iphone.png', 560), alto=520, basso=560); d = ImageDraw.Draw(im)
etichetta(d, (80, 86), 'Open hardware', BRONZE)
testo(d, (80, 132), 'Every KiCad file is on GitHub.', f(SB, 62))
y = H - 370
y = testo(d, (80, y), 'Like the board? Leave a star:', f(SB, 38))
y = testo(d, (80, y + 6), 'github.com/PZero/notapad', f(SB, 36), BRONZE)
testo(d, (80, y + 14), 'Next: why there are two microphones.', f(R_, 32), MUTE)
marchio(d); numero(d, 5, N); slides.append(im)

salva_carosello(slides, OUT); print('ok')
